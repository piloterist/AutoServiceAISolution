"use client";

import { useState } from "react";

import { AdminModal } from "@/components/settings/AdminModal";

type Topic = "new" | "existing" | "sources";

const TITLES: Record<Topic, string> = {
  new: "Конверсия новых клиентов: как считается",
  existing: "Конверсия существующих клиентов: как считается",
  sources: "Заказ-наряды после звонка и без звонка: как считается",
};

function Common() {
  return (
    <>
      <h4>Какие звонки считаются</h4>
      <ul>
        <li>
          Берутся звонки за выбранный период. Если выбран цех — звонки на линии этого цеха, а также звонки
          на линии других цехов, если по ним создан заказ-наряд выбранного цеха.
        </li>
        <li>
          Звонки сотрудников (номера из Настройки → Сотрудники) не учитываются нигде: ни в общем числе
          звонков, ни в целевых.
        </li>
        <li>
          <strong>Один номер телефона — один клиент.</strong> Сколько бы раз он ни звонил за период,
          считается один раз.
        </li>
      </ul>

      <h4>Что такое «целевой звонок»</h4>
      <p>
        Это настоящий разговор с клиентом о новом обращении: разговор длился не меньше 5 секунд и при этом
        либо система определила тему разговора (запись на ремонт, вопрос о стоимости и т. п.), либо
        разговор был дольше 20 секунд. Пропущенный звонок без разговора — не целевой. Исходящий звонок наш
        менеджер считается, только если это перезвон клиенту на его пропущенный звонок.
      </p>

      <h4>Звонки «по текущему заказу» — не целевые</h4>
      <p>
        Если клиент звонит узнать, <em>когда будет готова машина</em>, какой <em>статус</em> или{" "}
        <em>сроки</em>, или хочет забрать машину — это вопрос по уже идущему заказу, а не новое обращение.
        Такой звонок не считается целевым, если у клиента заказ-наряд сейчас в работе или закрыт не более
        3 дней назад. Определяется по теме разговора (смыслу), а не только по статусу заказ-наряда: если у клиента заказ в работе, но он
        звонит с новым вопросом (например, о стоимости дополнительных работ), звонок целевой.
      </p>
    </>
  );
}

function NewClients() {
  return (
    <>
      <p>
        Показывает, какая доля <strong>новых клиентов</strong> после разговора с нами дошла до заказ-наряда.
      </p>
      <Common />
      <h4>Строки справа от бублика</h4>
      <ul>
        <li>
          <strong>Всего звонков</strong> — все входящие и исходящие звонки периода (без сотрудников).
        </li>
        <li>
          <strong>Целевые звонки</strong> — сколько уникальных номеров дозвонились до целевого разговора
          (новые + существующие клиенты).
        </li>
        <li>
          <strong>Новые клиенты</strong> — из целевых номеров те, у кого <em>на момент звонка не было ни
          одного заказ-наряда</em> (в любом статусе). Гарантийные заказ-наряды не учитываются.
        </li>
        <li>
          <strong>Дошли до заказ-наряда</strong> — новые клиенты, у которых <em>после целевого звонка</em>{" "}
          создан хотя бы один (негарантийный) заказ-наряд. Заказ-наряд учитывается до следующего целевого
          разговора с этим номером: если он создан после него, он относится уже к тому разговору.
        </li>
        <li>
          <strong>Заказ-нарядов</strong> — сколько таких заказ-нарядов создано. У одного клиента их может быть
          несколько, поэтому число бывает больше, чем «дошли до заказ-наряда».
        </li>
        <li>
          <strong>Остались без ответа</strong> — новые номера, которым не дозвонились: был пропущенный звонок, а
          до конца периода им никто не перезвонил и разговора не было.
        </li>
      </ul>
      <h4>Процент в центре бублика</h4>
      <p>
        «Дошли до заказ-наряда» ÷ «Новые клиенты» × 100. Например: из 100 новых клиентов 15 дошли до
        заказ-наряда — конверсия 15%.
      </p>
      <h4>Что стоит учитывать</h4>
      <ul>
        <li>Свежие звонки ещё могут превратиться в заказ-наряд: цифры последних дней периода растут.</li>
        <li>
          Если по звонку заказ-наряд так и не создан, это может быть нормально: клиент уточнил цену и
          ушёл, не дозвонился и т. д. Здесь считается только факт заказ-наряда.
        </li>
      </ul>
      <p>Нажмите на любую цифру или на бублик — откроется список этих звонков в разделе Телефония → Конверсия.</p>
    </>
  );
}

function ExistingClients() {
  return (
    <>
      <p>
        То же самое для <strong>существующих клиентов</strong> — тех, у кого на момент звонка уже был хотя бы
        один заказ-наряд (в любом статусе: закрытый, отказ или ещё в работе).
      </p>
      <Common />
      <h4>Строки справа от бублика</h4>
      <ul>
        <li>
          <strong>Существующие клиенты</strong> — целевые номера, у которых к моменту звонка уже были
          заказ-наряды. Если заказ-наряд ещё не закрыт, номер всё равно считается: клиент мог позвонить, чтобы
          оформить новый заказ или добавить работы.
        </li>
        <li>
          <strong>Дошли до заказ-наряда</strong> и <strong>Заказ-нарядов</strong> — как у новых клиентов: после
          целевого звонка создан новый заказ-наряд (количество номеров и количество заказ-нарядов).
        </li>
        <li>
          <strong>Остались без ответа</strong> — существующие номера, которым не перезвонили.
        </li>
      </ul>
      <h4>Процент в центре бублика</h4>
      <p>«Дошли до заказ-наряда» ÷ «Существующие клиенты» × 100.</p>
      <p>Нажмите на любую цифру или на бублик — откроется список этих звонков в разделе Телефония → Конверсия.</p>
    </>
  );
}

function Sources() {
  return (
    <>
      <p>
        Откуда берутся заказ-наряды: после звонка клиента или без него. Это не про конверсию звонков, а про
        то, какая часть заказ-нарядов вообще приходит через телефон.
      </p>
      <h4>Какие заказ-наряды считаются</h4>
      <ul>
        <li>
          Все заказ-наряды, <strong>созданные</strong> в выбранном периоде (по дате создания), в любом статусе.
          Если выбран цех — заказ-наряды этого цеха.
        </li>
        <li>Гарантийные заказ-наряды не считаются; внутренние — если в Настройках включено «Исключить внутренние».</li>
      </ul>
      <h4>Два показателя</h4>
      <ul>
        <li>
          <strong>После звонка</strong> — заказ-наряд создан <em>после целевого звонка</em> клиента с этого же
          номера (того самого звонка, который учтён в конверсии слева). То есть клиент позвонил, поговорил, и
          мы оформили заказ.
        </li>
        <li>
          <strong>Без звонка</strong> — все остальные заказ-наряды: клиент приехал сам, звонил до начала
          периода, оформление шло по прежней записи, звонок был не целевой (например, очень короткий) или
          звонили не с этого номера.
        </li>
      </ul>
      <h4>Проценты</h4>
      <p>Доля считается от всех заказ-нарядов периода (после звонка + без звонка = 100%).</p>
      <p>
        Эти цифры помогают понять, насколько телефон является источником заказов, и не зависят от того, как
        мы делим клиентов на новых и существующих.
      </p>
    </>
  );
}

/** A small "?" next to a conversion card's title; opens a plain-language
 * description of how that card is counted (product ask, 2026-10-27). */
export function ConversionHelp({ topic }: { topic: Topic }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <button
        type="button"
        className="info-btn"
        aria-label="Как это считается"
        title="Как это считается"
        onClick={() => setOpen(true)}
      >
        ?
      </button>
      {open && (
        <AdminModal open title={TITLES[topic]} onClose={() => setOpen(false)} wide closeOnBackdropClick>
          <div className="conversion-help">
            {topic === "new" && <NewClients />}
            {topic === "existing" && <ExistingClients />}
            {topic === "sources" && <Sources />}
          </div>
          <div className="admin-form-actions">
            <span className="admin-form-actions-spacer" />
            <button type="button" className="admin-btn admin-btn-primary" onClick={() => setOpen(false)}>
              Понятно
            </button>
          </div>
        </AdminModal>
      )}
    </>
  );
}
